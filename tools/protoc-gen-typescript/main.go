// protoc-gen-typescript generates JSON transport types and named HTTP clients.
// It follows grpc-gateway's snake_case names and protobuf JSON int64 encoding.
package main

import (
	"fmt"
	annotations "google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
	"strings"
)

func prefix(d protoreflect.Descriptor) string {
	parts := strings.Split(string(d.ParentFile().Package()), ".")
	p := parts[len(parts)-2]
	return strings.ToUpper(p[:1]) + p[1:]
}
func name(d protoreflect.Descriptor) string { return prefix(d) + string(d.Name()) }
func fieldType(f protoreflect.FieldDescriptor) string {
	if f.IsMap() {
		return "Record<string, " + fieldType(f.MapValue()) + ">"
	}
	var t string
	switch f.Kind() {
	case protoreflect.MessageKind:
		switch f.Message().FullName() {
		case "google.protobuf.Struct":
			t = "JsonObject"
		case "google.protobuf.Value":
			t = "JsonValue"
		case "google.protobuf.Timestamp":
			t = "string"
		default:
			t = name(f.Message())
		}
	case protoreflect.StringKind, protoreflect.BytesKind:
		t = "string"
	case protoreflect.BoolKind:
		t = "boolean"
	case protoreflect.Int64Kind, protoreflect.Uint64Kind, protoreflect.Sint64Kind, protoreflect.Fixed64Kind, protoreflect.Sfixed64Kind:
		t = "Int64"
	default:
		t = "number"
	}
	if f.IsList() {
		t += "[]"
	}
	return t
}
func main() {
	protogen.Options{}.Run(func(p *protogen.Plugin) error {
		p.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		g := p.NewGeneratedFile("libs/frontend/api/src/generated.ts", "")
		g.P("// Code generated by protoc-gen-typescript. DO NOT EDIT.")
		g.P(`import { request } from "./http";`)
		g.P("export type JsonValue = null | boolean | number | string | JsonValue[] | JsonObject;")
		g.P("export interface JsonObject { [key: string]: JsonValue }")
		g.P("// Responses encode int64 as strings; protobuf JSON accepts strings or numbers in requests.")
		g.P("export type Int64 = string | number;")
		g.P("export type Input<T> = T extends readonly (infer E)[] ? Input<E>[] : T extends object ? { [K in keyof T]?: Input<T[K]> } : T;")
		var messages func([]*protogen.Message)
		messages = func(ms []*protogen.Message) {
			for _, m := range ms {
				if m.Desc.IsMapEntry() {
					continue
				}
				g.P("export interface ", name(m.Desc), " {")
				for _, f := range m.Fields {
					optional := ""
					if f.Desc.HasOptionalKeyword() || f.Desc.ContainingOneof() != nil {
						optional = "?"
					}
					g.P("  ", f.Desc.Name(), optional, ": ", fieldType(f.Desc), ";")
				}
				g.P("}")
				messages(m.Messages)
			}
		}
		for _, f := range p.Files {
			if f.Generate {
				messages(f.Messages)
			}
		}
		for _, f := range p.Files {
			if !f.Generate || len(f.Services) == 0 {
				continue
			}
			group := strings.ToLower(prefix(f.Desc))
			g.P("export const ", group, " = {")
			for _, s := range f.Services {
				for _, m := range s.Methods {
					rule, ok := proto.GetExtension(m.Desc.Options(), annotations.E_Http).(*annotations.HttpRule)
					if !ok {
						return fmt.Errorf("missing HTTP rule: %s", m.Desc.FullName())
					}
					url := rule.GetPost()
					if url == "" {
						return fmt.Errorf("only POST supported: %s", m.Desc.FullName())
					}
					method := string(m.Desc.Name())
					method = strings.ToLower(method[:1]) + method[1:]
					g.P("  ", method, ": (body: Input<", name(m.Input.Desc), "> = {}): Promise<", name(m.Output.Desc), "> => request(\"", url, "\", body),")
				}
			}
			g.P("};")
		}
		return nil
	})
}
